# Order in the table: first ASCII 0x20..0x7E, then the extra characters.
ASCII = [chr(c) for c in range(0x20, 0x7F)]
ZUSATZ = ['Ä', 'Ö', 'Ü', 'ä', 'ö', 'ü', 'ß', '°', '€', '§']
REIHENFOLGE = ASCII + ZUSATZ


def pruefen():
    """Each pattern must have 7 rows of 5 characters each, only '#' and '.' / ' '."""
    fehler = []
    for z in REIHENFOLGE:
        if z not in ART:
            fehler.append(f"{z!r}: missing")
            continue
        art = ART[z]
        if len(art) != 7 or any(len(zeile) != 5 for zeile in art):
            fehler.append(f"{z!r}: wrong dimensions")
        elif any(c not in "#. " for zeile in art for c in zeile):
            fehler.append(f"{z!r}: invalid character")
    return fehler


def spalten(zeichen):
    """Five column bytes, bit 0 = top row."""
    art = ART[zeichen]
    return [sum((1 << r) for r in range(7) if art[r][c] == '#') for c in range(5)]


def strom(text):
    """Expected column stream for a text - the reference for the check.

    Computed independently of the firmware: empty edge columns are trimmed,
    an empty column follows each character, the space is three columns
    wide. Unknown characters become '?'.
    """
    out = []
    for z in text:
        if z not in ART:
            z = '?'
        if z == ' ':
            out += [0, 0, 0, 0]
            continue
        sp = spalten(z)
        l, r = 0, 4
        while l < 4 and sp[l] == 0:
            l += 1
        while r > l and sp[r] == 0:
            r -= 1
        out += sp[l:r + 1] + [0]
    return out


