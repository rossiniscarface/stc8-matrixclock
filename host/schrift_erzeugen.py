#!/usr/bin/env python3
"""Generates firmware/schrift.h from the patterns in schrift_art.py.

Usage:  python3 schrift_erzeugen.py
"""
import os

import schrift_art as S

ZIEL = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "schrift.h")

fehler = S.pruefen()
if fehler:
    raise SystemExit("patterns faulty: " + "; ".join(fehler))

zeilen = []
for i, z in enumerate(S.REIHENFOLGE):
    name = {"\\": "\\\\", "'": "\\'"}.get(z, z)
    b = ", ".join(f"0x{v:02X}" for v in S.spalten(z))
    zeilen.append(f"    {{ {b} }},   /* {i:3d}  {z} */")

kopf = f'''/* GENERATED by host/schrift_erzeugen.py from host/schrift_art.py - do not edit by hand.
 *
 * {len(S.REIHENFOLGE)} characters, 5 columns each, bit 0 = top row.
 * Index 0..94 is ASCII 0x20..0x7E, followed by the extra characters:
 *   95 Ä  96 Ö  97 Ü  98 ä  99 ö  100 ü  101 ß  102 degree  103 euro  104 section sign
 * Variable width: the firmware trims empty edge columns when building the
 * scrolling-text stream.
 */
#define SCHRIFT_ANZAHL {len(S.REIHENFOLGE)}
#define G_AE 95
#define G_OE 96
#define G_UE 97
#define G_ae 98
#define G_oe 99
#define G_ue 100
#define G_SS 101
#define G_GRAD 102
#define G_EURO 103
#define G_PARA 104

static const __code uint8_t SCHRIFT[SCHRIFT_ANZAHL][5] = {{
'''
open(ZIEL, "w").write(kopf + "\n".join(zeilen) + "\n};\n")
print(f"firmware/schrift.h written, {len(S.REIHENFOLGE)} characters, {len(S.REIHENFOLGE) * 5} bytes")
